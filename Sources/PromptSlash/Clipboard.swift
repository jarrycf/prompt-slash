import AppKit

/// 最近复制 / 剪切的一条纯文本（只存在内存里，不写入磁盘）
struct ClipItem: Identifiable, Equatable {
    let id: String
    let text: String
    let date: Date

    init(text: String, date: Date = Date()) {
        self.id = "clip-" + UUID().uuidString
        self.text = text
        self.date = date
    }

    /// 列表里显示的一行
    var line: String {
        text.split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }
            .first { !$0.isEmpty } ?? text
    }
}

enum ClipboardPolicy {
    /// 最多保留几条
    static let limit = 3
    /// 单条最多保留的字符数（避免超大文本占内存）
    static let maxLength = 200_000
    /// Prompt Slash 自己写入剪贴板时带上这个类型，监听时跳过
    static let internalType = NSPasteboard.PasteboardType("io.github.jarrycf.promptslash.internal")
    /// 密码管理器等会用这些类型标记「不要记录」的内容（nspasteboard.org 约定）
    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        internalType,
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        .fileURL, // 访达里复制的文件
    ]

    /// 把新内容放到最前面：重复的只移动不新增，超过上限就挤掉最旧的
    static func inserting(_ text: String, into items: [ClipItem], date: Date = Date()) -> [ClipItem] {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return items }
        let clipped = text.count > maxLength ? String(text.prefix(maxLength)) : text
        var result = items.filter { $0.text != clipped }
        result.insert(ClipItem(text: clipped, date: date), at: 0)
        return Array(result.prefix(limit))
    }

    /// 写剪贴板并标记为本应用写入
    static func write(_ string: String, to pb: NSPasteboard = .general) {
        pb.clearContents()
        pb.setString(string, forType: .string)
        pb.setData(Data(), forType: internalType)
    }
}

/// 轮询系统剪贴板（每 0.5 秒），把新的纯文本交给 AppModel
@MainActor
final class ClipboardWatcher {
    private let model: AppModel
    private var timer: Timer?
    private var lastChange: Int
    /// 防止 App Nap 在后台挂起轮询
    private let activity = ProcessInfo.processInfo.beginActivity(
        options: [.userInitiatedAllowingIdleSystemSleep], reason: "监听剪贴板"
    )

    init(model: AppModel) {
        self.model = model
        lastChange = -1 // 启动时也把当前剪贴板的内容收进来
        tick()
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        t.tolerance = 0.2
        RunLoop.main.add(t, forMode: .common) // 菜单展开、窗口拖动时也照常检查
        timer = t
    }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: ClipboardPolicy.ignoredTypes),
              let text = pb.string(forType: .string) else { return }
        model.addClip(text)
    }
}
